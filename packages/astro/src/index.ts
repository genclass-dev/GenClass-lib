// @genclass/astro: the GenClass runtime as an Astro integration. Role: in `astro:config:setup`, inject into every page
// the runtime's own one line (`import "@genclass/runtime/auto"`, or `/auto/guard`) as a `page` script, which Vite
// bundles with the page's other scripts, plus, when the options need it, a virtual module imported before the runtime
// that sets `window.GENCLASS_CONFIG` (token, telemetry). Invariants: browser only (a page script never runs on the
// server, and the integration itself runs at config time only); GenClass behaves exactly as with the one-line install
// (observe by default, automatic state discovery for React islands, the `?genclass=off` kill switch, a
// `<meta name="genclass">` tag still read); the devtools overlay line is injected in `astro dev` only unless
// `devtools: "always"` asks for it. The generated code is pure (pageScript, configSource), so the tests check it exactly.

import type { AstroIntegration } from "astro";

/** Options of `genclass(options)` in astro.config. */
export interface GenClassOptions {
  /**
   * "observe" (default): GenClass reports what it finds (one console line per finding, the devtools overlay) and
   * never holds, delays or changes anything. "guard": it may also take small, reversible actions (drop a stale
   * response, reuse a duplicate's result) when its model is confident.
   */
  mode?: "observe" | "guard";
  /**
   * The app's dashboard token (`gc_...`) from genclass.dev or `npx @genclass/runtime login`. Needs `@genclass/runtime`
   * 0.3.0 or later; 0.2.x ignores it.
   */
  token?: string;
  /**
   * Anonymous, redacted diagnostics to the GenClass maintainers (packages/runtime/TELEMETRY.md). Unset: the runtime's
   * default (on from public hosts, off on localhost and private networks). `false`: off. `true`: an explicit opt-in
   * that also sends from local hosts.
   */
  telemetry?: boolean;
  /**
   * The devtools overlay: "dev" (default) loads it in `astro dev` only, "always" also in production builds, "never"
   * not at all. The overlay is a lazy chunk that is never part of the first load.
   */
  devtools?: "dev" | "always" | "never";
}

export const MODES: readonly string[] = ["observe", "guard"];
export const DEVTOOLS: readonly string[] = ["dev", "always", "never"];

/** The virtual module that sets window.GENCLASS_CONFIG (resolved by the Vite plugin the integration adds). */
export const CONFIG_MODULE = "virtual:@genclass/astro/config";
const RESOLVED_CONFIG_MODULE = `\0${CONFIG_MODULE}`;

/** Throws, with a plain message, on a value the runtime does not take. */
export function validate(options: GenClassOptions): void {
  if (options.mode !== undefined && !MODES.includes(options.mode)) {
    throw new Error(`[@genclass/astro] mode must be "observe" or "guard" (got ${JSON.stringify(options.mode)})`);
  }
  if (options.devtools !== undefined && !DEVTOOLS.includes(options.devtools)) {
    throw new Error(`[@genclass/astro] devtools must be "dev", "always" or "never" (got ${JSON.stringify(options.devtools)})`);
  }
  if (options.token !== undefined && typeof options.token !== "string") {
    throw new Error(`[@genclass/astro] token must be a string (got ${JSON.stringify(options.token)})`);
  }
  if (options.telemetry !== undefined && typeof options.telemetry !== "boolean") {
    throw new Error(`[@genclass/astro] telemetry must be true or false (got ${JSON.stringify(options.telemetry)})`);
  }
}

/** The options that become `window.GENCLASS_CONFIG` (token, telemetry), or null when there are none. */
export function pageConfig(options: GenClassOptions): { token?: string; telemetry?: boolean } | null {
  const cfg: { token?: string; telemetry?: boolean } = {};
  if (typeof options.token === "string" && options.token !== "") cfg.token = options.token;
  if (typeof options.telemetry === "boolean") cfg.telemetry = options.telemetry;
  return Object.keys(cfg).length ? cfg : null;
}

/** The runtime entry the page script imports for a mode. */
export function entryFor(mode: GenClassOptions["mode"]): string {
  return mode === "guard" ? "@genclass/runtime/auto/guard" : "@genclass/runtime/auto";
}

/** Whether the overlay loads: "always", or "dev" under `astro dev`. */
export function overlayFor(devtools: GenClassOptions["devtools"], dev: boolean): boolean {
  return devtools === "always" || ((devtools ?? "dev") === "dev" && dev);
}

/** The virtual config module: sets window.GENCLASS_CONFIG. Keys already set on the page (a head script) win. */
export function configSource(cfg: { token?: string; telemetry?: boolean }): string {
  return [
    "// Page configuration for GenClass, generated by @genclass/astro from astro.config. The injected page script imports",
    "// this module before @genclass/runtime/auto, which reads window.GENCLASS_CONFIG once when it starts. Keys already set",
    "// on the page (for example by a head script) win over these.",
    'if (typeof window !== "undefined") {',
    `  window.GENCLASS_CONFIG = Object.assign(${JSON.stringify(cfg)}, window.GENCLASS_CONFIG);`,
    "}",
    "",
  ].join("\n");
}

/** The `page` script injected into every page. `dev` is whether the command is `astro dev`. */
export function pageScript(options: GenClassOptions, dev: boolean): string {
  const entry = entryFor(options.mode);
  const overlay = overlayFor(options.devtools, dev);
  const withConfig = pageConfig(options) !== null;
  return [
    ...(withConfig ? [`import "${CONFIG_MODULE}";`] : []),
    overlay ? `import genclass from "${entry}";` : `import "${entry}";`,
    ...(overlay ? ['import("@genclass/runtime/devtools").then((d) => d.mountDevtools(genclass));'] : []),
    "",
  ].join("\n");
}

/**
 * The runtime modules the page script imports, for Vite's `optimizeDeps.include`: the script is a virtual module, so
 * Vite's dependency scan does not see them, and without this it discovers them on the first page request and
 * re-optimizes with a reload (a "504 Outdated Optimize Dep" in the console).
 */
export function runtimeImports(options: GenClassOptions, dev: boolean): string[] {
  const entry = entryFor(options.mode);
  return overlayFor(options.devtools, dev) ? [entry, "@genclass/runtime/devtools"] : [entry];
}

/**
 * The integration. `astro.config.mjs`: `import genclass from "@genclass/astro"; export default defineConfig({
 * integrations: [genclass()] })`, or `genclass({ mode: "guard", telemetry: false })`.
 */
export default function genclass(options: GenClassOptions = {}): AstroIntegration {
  validate(options);
  return {
    name: "@genclass/astro",
    hooks: {
      "astro:config:setup": ({ command, injectScript, updateConfig }) => {
        const dev = command === "dev";
        const cfg = pageConfig(options);
        const source = cfg ? configSource(cfg) : null;
        updateConfig({
          vite: {
            optimizeDeps: { include: runtimeImports(options, dev) },
            plugins: source
              ? [
                  {
                    name: "@genclass/astro:config",
                    resolveId: (id: string) => (id === CONFIG_MODULE ? RESOLVED_CONFIG_MODULE : undefined),
                    load: (id: string) => (id === RESOLVED_CONFIG_MODULE ? source : undefined),
                  },
                ]
              : [],
          },
        });
        injectScript("page", pageScript(options, dev));
      },
    },
  };
}
