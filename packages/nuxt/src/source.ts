// What @genclass/nuxt generates: the client-only Nuxt plugin that starts GenClass, and the page-configuration module
// it imports first. Pure functions of the module options and of whether this is a development server, so the tests can
// check the exact output. Invariants: the plugin imports the runtime's own zero-code entry (`@genclass/runtime/auto`,
// or `/auto/guard`), so GenClass behaves exactly as with the one-line install (observe by default, automatic state
// discovery, the `?genclass=off` kill switch, a `<meta name="genclass">` tag still read); the options that are not the
// import path (token, telemetry) travel as `window.GENCLASS_CONFIG`, the page configuration the runtime documents, in a
// module imported before the runtime (an ES module's imports evaluate before its own body, so the config is set when
// the runtime starts); the devtools overlay line is only generated when the overlay should load, so a production
// build carries no reference to it unless `devtools: "always"` asks for one.

/** Options of the `genclass` key in nuxt.config. */
export interface ModuleOptions {
  /**
   * "observe" (default): GenClass reports what it finds (one console line per finding, the devtools overlay) and
   * never holds, delays or changes anything. "guard": it may also take small, reversible actions (drop a stale
   * response, reuse a duplicate's result) when its model is confident.
   */
  mode?: "observe" | "guard";
  /**
   * The app's dashboard token (`gc_...`) from genclass.dev or `npx @genclass/runtime@beta login`. Needs `@genclass/runtime`
   * 0.3.0 or later; 0.2.x ignores it.
   */
  token?: string;
  /**
   * Anonymous, redacted diagnostics to the GenClass maintainers (packages/runtime/TELEMETRY.md). Unset: the runtime's
   * default (on from public hosts, off on localhost and private networks). `false`: off. `true`: an explicit opt-in
   * that also sends from local hosts.
   */
  telemetry?: boolean;
  /**
   * The devtools overlay: "dev" (default) loads it in `nuxt dev` only, "always" also in production builds, "never"
   * not at all. The overlay is a lazy chunk that is never part of the first load.
   */
  devtools?: "dev" | "always" | "never";
}

export const MODES: readonly string[] = ["observe", "guard"];
export const DEVTOOLS: readonly string[] = ["dev", "always", "never"];

/** Throws, with a plain message, on a value the runtime does not take. Unknown keys are left to Nuxt's own typing. */
export function validate(options: ModuleOptions): void {
  if (options.mode !== undefined && !MODES.includes(options.mode)) {
    throw new Error(`[@genclass/nuxt] genclass.mode must be "observe" or "guard" (got ${JSON.stringify(options.mode)})`);
  }
  if (options.devtools !== undefined && !DEVTOOLS.includes(options.devtools)) {
    throw new Error(`[@genclass/nuxt] genclass.devtools must be "dev", "always" or "never" (got ${JSON.stringify(options.devtools)})`);
  }
  if (options.token !== undefined && typeof options.token !== "string") {
    throw new Error(`[@genclass/nuxt] genclass.token must be a string (got ${JSON.stringify(options.token)})`);
  }
  if (options.telemetry !== undefined && typeof options.telemetry !== "boolean") {
    throw new Error(`[@genclass/nuxt] genclass.telemetry must be true or false (got ${JSON.stringify(options.telemetry)})`);
  }
}

/** The options that become `window.GENCLASS_CONFIG` (token, telemetry), or null when there are none. */
export function pageConfig(options: ModuleOptions): { token?: string; telemetry?: boolean } | null {
  const cfg: { token?: string; telemetry?: boolean } = {};
  if (typeof options.token === "string" && options.token !== "") cfg.token = options.token;
  if (typeof options.telemetry === "boolean") cfg.telemetry = options.telemetry;
  return Object.keys(cfg).length ? cfg : null;
}

/** The runtime entry the plugin imports for a mode. */
export function entryFor(mode: ModuleOptions["mode"]): string {
  return mode === "guard" ? "@genclass/runtime/auto/guard" : "@genclass/runtime/auto";
}

/** Whether the overlay loads: "always", or "dev" on a development server. */
export function overlayFor(devtools: ModuleOptions["devtools"], dev: boolean): boolean {
  return devtools === "always" || ((devtools ?? "dev") === "dev" && dev);
}

/** `#build/genclass.config.mjs`: sets window.GENCLASS_CONFIG. Keys already set on the page (a head script) win. */
export function configSource(cfg: { token?: string; telemetry?: boolean }): string {
  return [
    "// Page configuration for GenClass, generated by @genclass/nuxt from nuxt.config (genclass: { ... }). The GenClass",
    "// plugin imports this module before @genclass/runtime/auto, which reads window.GENCLASS_CONFIG once when it starts.",
    "// Keys already set on the page (for example by a head script) win over these.",
    'if (typeof window !== "undefined") {',
    `  window.GENCLASS_CONFIG = Object.assign(${JSON.stringify(cfg)}, window.GENCLASS_CONFIG);`,
    "}",
    "",
  ].join("\n");
}

/** `genclass.client.mjs`: the client-only plugin. `dev` is `nuxt.options.dev` (a development server). */
export function pluginSource(options: ModuleOptions, dev: boolean): string {
  const mode = options.mode ?? "observe";
  const entry = entryFor(mode);
  const overlay = overlayFor(options.devtools, dev);
  const withConfig = pageConfig(options) !== null;
  const what =
    mode === "guard"
      ? "lets GenClass act when its model is confident (small, reversible actions)"
      : "observes (reports what it sees, never changes anything)";
  return [
    "// GenClass goes first, before Nuxt's app and its first requests, in the browser only (generated by @genclass/nuxt from",
    `// nuxt.config). "${entry}" ${what}. Add ?genclass=off to the URL to turn it off for a page load.`,
    ...(withConfig ? ['import "#build/genclass.config.mjs";'] : []),
    overlay ? `import genclass from "${entry}";` : `import "${entry}";`,
    'import { defineNuxtPlugin } from "#app";',
    "",
    ...(overlay
      ? [
          "export default defineNuxtPlugin(() => {",
          "  // The devtools overlay (a lazy chunk, never in the first load).",
          '  import("@genclass/runtime/devtools").then((d) => d.mountDevtools(genclass));',
          "});",
        ]
      : ["export default defineNuxtPlugin(() => {});"]),
    "",
  ].join("\n");
}
