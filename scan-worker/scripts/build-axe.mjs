// Writes src/axe-source.ts from node_modules/axe-core/axe.min.js, the version package.json pins (npm ci first). The
// file is embedded unmodified, with axe-core's own copyright and Mozilla Public License 2.0 notice at its top; the
// generated module repeats where it came from, its license and where its source is. test/axe.test.ts fails when the
// committed src/axe-source.ts is not byte for byte this build of the installed package.
//
//   node scripts/build-axe.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const pkg = JSON.parse(readFileSync(new URL("node_modules/axe-core/package.json", root), "utf8"));
const src = readFileSync(new URL("node_modules/axe-core/axe.min.js", root), "utf8");
const pinned = JSON.parse(readFileSync(new URL("package.json", root), "utf8")).dependencies["axe-core"];
if (pkg.version !== pinned) throw new Error(`node_modules has axe-core ${pkg.version}, package.json pins ${pinned}: run npm ci`);
const notice = /^\/\*![\s\S]*?\*\//.exec(src);
if (!notice || !notice[0].includes(`axe v${pkg.version}`) || !notice[0].includes("Mozilla Public")) throw new Error("axe.min.js does not start with its copyright and MPL-2.0 notice");
const build = { version: pkg.version, sha256: createHash("sha256").update(src).digest("hex"), bytes: Buffer.byteLength(src), license: pkg.license };
const header = notice[0]
  .replace(/^\/\*!\s?/, "")
  .replace(/\s*\*\/$/, "")
  .split("\n")
  .map((l) => `//   ${l.replace(/^\s*\*\s?/, "")}`.trimEnd())
  .join("\n");
const out =
  `// Generated by scripts/build-axe.mjs from axe-core ${pkg.version} (node_modules/axe-core/axe.min.js). Do not edit.\n` +
  `// axe-core is licensed under the Mozilla Public License 2.0 (MPL-2.0); its source code is at\n` +
  `// https://github.com/dequelabs/axe-core (tag v${pkg.version}). The embedded file is unmodified and keeps its notice:\n` +
  `${header}\n` +
  `// axe-core includes code under the MIT License listed in node_modules/axe-core/LICENSE-3RD-PARTY.txt.\n` +
  `export const AXE_BUILD = ${JSON.stringify(build)} as const;\n` +
  `export const AXE_SOURCE: string = ${JSON.stringify(src)};\n`;
writeFileSync(new URL("src/axe-source.ts", root), out);
console.log(`wrote src/axe-source.ts: axe-core ${build.version}, ${build.bytes} bytes, sha256 ${build.sha256}`);
