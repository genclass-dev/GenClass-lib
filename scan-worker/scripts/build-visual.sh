#!/bin/sh
# Builds the GenClass visual checks (packages/runtime/src/visual on branch wave2/visual) into src/visual-source.ts,
# so the scanner injects them instead of its built-in subset and can turn their fixes on in the with-GenClass pass.
# Run on CI or a VM, never on the owner's Mac (repo rule: no runtime builds there):
#
#   git fetch origin wave2/visual && git worktree add /tmp/visual origin/wave2/visual
#   sh scan-worker/scripts/build-visual.sh /tmp/visual
#
# The entry must be an IIFE-friendly module that assigns
#   window.__genclassScanChecks(options) -> { findings: RawFinding[], notes: string[], page }   (see src/checks.ts)
#   window.__genclassScanFixes(findings) -> { applied: { kind, selector, how }[] }               (optional)
# using the finding kinds in src/catalog.ts. Default entry: packages/runtime/src/visual/scan-entry.ts.
set -eu
src=${1:?usage: build-visual.sh <checkout of wave2/visual> [entry]}
entry=${2:-packages/runtime/src/visual/scan-entry.ts}
here=$(cd "$(dirname "$0")/.." && pwd)
[ -f "$src/$entry" ] || { echo "no $entry in $src: wave2/visual has no scanner entry yet" >&2; exit 1; }
out=$(mktemp -d)
npx --yes esbuild@0.27.0 "$src/$entry" --bundle --format=iife --minify --target=chrome120 --outfile="$out/visual.js"
node -e '
const fs = require("fs");
const js = fs.readFileSync(process.argv[1], "utf8");
if (!/__genclassScanChecks/.test(js)) { console.error("the chunk does not define window.__genclassScanChecks"); process.exit(1); }
const head = "// Generated by scripts/build-visual.sh from " + process.argv[3] + ". Do not edit.\n";
fs.writeFileSync(process.argv[2], head + "export const VISUAL_SOURCE: string | null = " + JSON.stringify(js) + ";\n");
' "$out/visual.js" "$here/src/visual-source.ts" "$(git -C "$src" rev-parse --short HEAD 2>/dev/null || echo unknown):$entry"
echo "wrote $here/src/visual-source.ts ($(wc -c < "$out/visual.js") bytes of chunk)"
