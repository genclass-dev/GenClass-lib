#!/bin/sh
# Bundles the GenClass visual chunk into the scanner: visual/scan-entry.js (the scanner's side) plus the runtime's lazy
# visual chunk, packages/runtime/dist/visual/index.js from a checkout of wave2/visual that has been built, into one
# IIFE, written as src/visual-source.ts (VISUAL_SOURCE, and VISUAL_BUILD with where it came from).
#
# CI does this (.github/workflows/ci.yml, job scan-visual): it builds the runtime at the pinned commit, runs this
# script, uploads the result as the artifact scan-visual, and fails when the committed src/visual-source.ts differs.
# Never on the owner's Mac (repo rule: no runtime builds there). To update the chunk: change VISUAL_REF in ci.yml,
# run the job (gh workflow run ci.yml --ref <branch>), download the artifact over src/visual-source.ts, commit.
#
#   sh scan-worker/scripts/build-visual.sh <built checkout of wave2/visual> [output file]
set -eu
src=${1:?usage: build-visual.sh <built checkout of wave2/visual> [output]}
here=$(cd "$(dirname "$0")/.." && pwd)
out=${2:-$here/src/visual-source.ts}
chunk="$src/packages/runtime/dist/visual/index.js"
[ -f "$chunk" ] || { echo "no $chunk: build the runtime first (npm ci && npm run build -w @genclass/runtime)" >&2; exit 1; }
work=$(mktemp -d)
cp -R "$src/packages/runtime/dist" "$work/dist"
cp "$here/visual/scan-entry.js" "$work/scan-entry.js"
npx --yes esbuild@0.27.0 "$work/scan-entry.js" --bundle --format=iife --minify --target=chrome120 --legal-comments=none --log-level=warning --outfile="$work/visual.js"
commit=$(git -C "$src" rev-parse HEAD)
node -e '
const fs = require("fs");
const { createHash } = require("crypto");
const [bundle, chunk, out, commit] = process.argv.slice(1);
const js = fs.readFileSync(bundle, "utf8");
if (!js.includes("__genclassScanVisual")) { console.error("the bundle does not define window.__genclassScanVisual"); process.exit(1); }
const sha = (b) => createHash("sha256").update(b).digest("hex");
const build = { commit, chunkSha256: sha(fs.readFileSync(chunk)), bundleSha256: sha(js), bytes: Buffer.byteLength(js) };
fs.writeFileSync(out,
  "// Generated by scripts/build-visual.sh on CI (job scan-visual) from wave2/visual " + commit + ". Do not edit.\n" +
  "// visual/scan-entry.js bundled with packages/runtime/dist/visual/index.js (sha256 " + build.chunkSha256 + ").\n" +
  "export const VISUAL_BUILD = " + JSON.stringify(build) + " as const;\n" +
  "export const VISUAL_SOURCE: string | null = " + JSON.stringify(js) + ";\n");
console.log("wrote " + out + ": " + build.bytes + " bytes, chunk sha256 " + build.chunkSha256);
' "$work/visual.js" "$chunk" "$out" "$commit"
rm -rf "$work"
