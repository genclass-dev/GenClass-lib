// Regenerates the IANA top-level domain list used by the scanner (scan-worker/src/tlds.ts) and by the site worker's
// genclass.dev/<url> rule (site/src/tlds.js). The two copies must stay identical (test/tlds.test.ts checks it).
//
//   node scan-worker/scripts/update-tlds.mjs                 # fetches https://data.iana.org/TLD/tlds-alpha-by-domain.txt
//   node scan-worker/scripts/update-tlds.mjs /path/tlds.txt  # or reads a downloaded copy
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch("https://data.iana.org/TLD/tlds-alpha-by-domain.txt")).text();
const lines = src.split(/\r?\n/);
const version = (lines[0].match(/Version (\d+)/) || [])[1];
if (!version) throw new Error("not an IANA TLD list (no version line)");
const tlds = lines.filter((l) => l && !l.startsWith("#")).map((l) => l.trim().toLowerCase());
if (tlds.length < 1000 || tlds.some((t) => !/^[a-z0-9-]+$/.test(t))) throw new Error("unexpected TLD list contents");
const body = tlds.join(" ");
const head = (lang) =>
  `// Generated by scan-worker/scripts/update-tlds.mjs from the IANA root zone list, version ${version}. Do not edit.\n` +
  `// ${tlds.length} top-level domains (internationalised ones in their xn-- form).\n`;
writeFileSync(
  resolve(here, "../src/tlds.ts"),
  `${head("ts")}export const TLD_VERSION = "${version}";\nexport const TLDS: ReadonlySet<string> = new Set(\n  "${body}".split(" "),\n);\n`,
);
writeFileSync(
  resolve(here, "../../site/src/tlds.js"),
  `${head("js")}export const TLD_VERSION = "${version}";\nexport const TLDS = new Set(\n  "${body}".split(" "),\n);\n`,
);
console.log(`wrote ${tlds.length} TLDs (IANA version ${version})`);
